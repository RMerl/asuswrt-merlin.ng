/** Issue a Micro Control command through the uC DSC Command Interface. Control returned only after command is finished.
 * @param[in] sa__ is an opaque state vector passed through to device access functions.
 * @param[in] control Micro Control command to be issued
 * @param[in] timeout_ms Time interval in milliseconds inside which the command should be completed; else error issued
 * @return Error Code generated by API (returns ERR_CODE_NONE if no errors)
 */
