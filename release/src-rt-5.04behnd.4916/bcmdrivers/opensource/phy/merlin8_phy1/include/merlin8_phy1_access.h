/*---------------------------------------------------*/
/*  Micro Commands through uC DSC Command Interface  */
/*---------------------------------------------------*/
/** Issue a Micro command through the uC DSC Command Interface and return control immediately.
 * @param[in] sa__ is an opaque state vector passed through to device access functions.
 * @param[in] cmd Micro command to be issued
 * @param[in] supp_info Supplement information for the Micro command to be issued (RAM read/write address or Micro Control command)
 * @return Error Code generated by API (returns ERR_CODE_NONE if no errors)
 */
err_code_t merlin8_phy1_pmd_uc_cmd_return_immediate(srds_access_t *sa__, enum srds_pmd_uc_cmd_enum cmd, uint8_t supp_info);

/** Issue a Micro command through the uC DSC Command Interface. Control returned only after command is finished.
 * @param[in] sa__ is an opaque state vector passed through to device access functions.
 * @param[in] cmd Micro command to be issued
 * @param[in] supp_info Supplement information for the Micro command to be issued (RAM read/write address or Micro Control command)
 * @param[in] timeout_ms Time interval in milliseconds inside which the command should be completed; else error issued
 * @return Error Code generated by API (returns ERR_CODE_NONE if no errors)
 */
err_code_t merlin8_phy1_pmd_uc_cmd(srds_access_t *sa__, enum srds_pmd_uc_cmd_enum cmd, uint8_t supp_info, uint32_t timeout_ms);

/** Issue a Micro command with data through the uC DSC Command Interface and return control immediately.
 * @param[in] sa__ is an opaque state vector passed through to device access functions.
 * @param[in] cmd Micro command to be issued
 * @param[in] supp_info Supplement information for the Micro command to be issued (RAM write address)
 * @param[in] data Data to be written to dsc_data for use by uC
 * @return Error Code generated by API (returns ERR_CODE_NONE if no errors)
 */
err_code_t merlin8_phy1_pmd_uc_cmd_with_data_return_immediate(srds_access_t *sa__, enum srds_pmd_uc_cmd_enum cmd, uint8_t supp_info, uint16_t data);

/** Issue a Micro command with data through the uC DSC Command Interface. Control returned only after command is finished.
 * @param[in] sa__ is an opaque state vector passed through to device access functions.
 * @param[in] cmd Micro command to be issued
 * @param[in] supp_info Supplement information for the Micro command to be issued (RAM write address)
 * @param[in] data Data to be written to dsc_data for use by uC
 * @param[in] timeout_ms Time interval in milliseconds inside which the command should be completed; else error issued
 * @return Error Code generated by API (returns ERR_CODE_NONE if no errors)
 */
err_code_t merlin8_phy1_pmd_uc_cmd_with_data(srds_access_t *sa__, enum srds_pmd_uc_cmd_enum cmd, uint8_t supp_info, uint16_t data, uint32_t timeout_ms);

/** Issue a Micro Control command through the uC DSC Command Interface and return control immediately.
 * @param[in] sa__ is an opaque state vector passed through to device access functions.
 * @param[in] control Micro Control command to be issued
 * @return Error Code generated by API (returns ERR_CODE_NONE if no errors)
 */
