/*! uCode info
 * This struct should be populated from the values found in the ucode image .h file
 * Note: If UCODE_DR_CODE_SIZE_KB does not appear in the image .h file,
 *       then set ucode_dr_code_size_kb to 0.
 */
typedef struct {
    /** UCODE_IMAGE_SIZE */
    uint32_t ucode_size;
    /** UCODE_STACK_SIZE */
    uint16_t stack_size;
    /** UCODE_IMAGE_CRC */
    uint16_t crc_value;
    /** UCODE_DR_CODE_SIZE_KB */
    uint8_t ucode_dr_code_size_kb;
} ucode_info_t;

