#define get_endian_offset(addr) (merlin8_phy1_INTERNAL_is_big_endian() ? \
                                (\
                                (((USR_UINTPTR)(addr))%4 == 0) ?  3 : \
                                (((USR_UINTPTR)(addr))%4 == 1) ?  1 : \
                                (((USR_UINTPTR)(addr))%4 == 2) ? -1 : \
                                (((USR_UINTPTR)(addr))%4 == 3) ? -3 : \
                                0) \
                                : 0)

